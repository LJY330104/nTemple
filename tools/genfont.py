#!/usr/bin/env python3
"""Bake a 6x8 pixel font into a C header for the nTemple clone."""
from PIL import Image, ImageDraw, ImageFont
import sys

CHARS = " " + "!\"#$%&'()*+,-./0123456789:;<=>?@" + "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
W, H = 6, 8
FONT = "/System/Library/Fonts/Menlo.ttc"
SIZE = 10
THRESH = 90

def main(out_path):
    font = ImageFont.truetype(FONT, SIZE, index=0)
    glyphs = []
    art = []
    for ch in CHARS:
        img = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(img)
        bb = d.textbbox((0, 0), ch, font=font)
        d.text((0, (H - 1) - bb[3]), ch, font=font, fill=255)
        px = img.load()
        rows = []
        for y in range(H):
            bits = 0
            for x in range(W):
                if px[x, y] > THRESH:
                    bits |= 1 << (W - 1 - x)
            rows.append(bits)
        glyphs.append(rows)
        art.append((ch, rows))

    with open(out_path, "w") as f:
        f.write("/* generated by tools/genfont.py -- 6x8 mono font */\n")
        f.write("#ifndef FONT_DATA_H\n#define FONT_DATA_H\n\n")
        f.write("#define FONT_W 6\n#define FONT_H 8\n")
        f.write("#define FONT_FIRST 32\n#define FONT_COUNT %d\n\n" % len(CHARS))
        f.write("static const unsigned char font_bits[FONT_COUNT][FONT_H] = {\n")
        for ch, rows in art:
            f.write("    {" + ", ".join("0x%02X" % r for r in rows) + "}, /* %s */\n"
                    % ("space" if ch == " " else ch))
        f.write("};\n\n#endif\n")

    sys.stderr.write("".join("%s%s\n" % (c, "".join("\n " if i else "" for i in range(0))) for c, _ in []))
    for ch, rows in art:
        if ch in "0123456789AZ":  # sanity preview
            sys.stderr.write("--- '%s'\n" % ch)
            for r in rows:
                sys.stderr.write("".join("#" if r & (1 << (W - 1 - x)) else "." for x in range(W)) + "\n")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "font_data.h")
